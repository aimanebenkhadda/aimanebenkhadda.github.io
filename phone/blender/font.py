G = {}
def g(ch, top, rows):
    """top = first row index the given rows start at."""
    w = max(len(r) for r in rows) if rows else 0
    full = ['.' * w] * 10
    for i, r in enumerate(rows):
        full[top + i] = r.ljust(w, '.')
    G[ch] = full

def caps(ch, rows): g(ch, 1, rows)
def xh(ch, rows): g(ch, 3, rows)

