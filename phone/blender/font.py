# accents ------------------------------------------------------------
def overlay(base, marks, name):
    rows = [list(r) for r in G[base]]
    w = len(rows[0])
    c = w // 2
    for (r, dx) in marks:
        x = c + dx
        if 0 <= x < w:
            rows[r][x] = '#'
    G[name] = [''.join(r) for r in rows]

LOW = {'acute': [(1, 1), (2, 0)], 'grave': [(1, -1), (2, 0)], 'circ': [(1, 0), (2, -1), (2, 1)],
       'trema': [(1, -1), (1, 1)], 'ring': [(1, 0)]}
CAP = {'acute': [(0, 0), (0, 1)], 'grave': [(0, -1), (0, 0)], 'circ': [(0, -1), (0, 1)], 'trema': [(0, -1), (0, 1)]}
for b, acc in [('a', 'grave'), ('a', 'circ'), ('a', 'trema'), ('a', 'acute'), ('e', 'acute'), ('e', 'grave'), ('e', 'circ'), ('e', 'trema'),
               ('o', 'circ'), ('o', 'trema'), ('o', 'acute'), ('u', 'grave'), ('u', 'circ'), ('u', 'trema'), ('u', 'acute')]:
    name = {'grave': {'a': 'à', 'e': 'è', 'u': 'ù'}, 'circ': {'a': 'â', 'e': 'ê', 'o': 'ô', 'u': 'û'},
            'trema': {'a': 'ä', 'e': 'ë', 'o': 'ö', 'u': 'ü'}, 'acute': {'a': 'á', 'e': 'é', 'o': 'ó', 'u': 'ú'}}[acc][b]
    overlay(b, LOW[acc], name)
for b, acc, name in [('A', 'grave', 'À'), ('A', 'circ', 'Â'), ('E', 'acute', 'É'), ('E', 'grave', 'È'), ('E', 'circ', 'Ê'), ('O', 'circ', 'Ô'), ('U', 'grave', 'Ù'), ('U', 'circ', 'Û')]:
    overlay(b, CAP[acc], name)
