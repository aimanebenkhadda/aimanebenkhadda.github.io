"""Hand-made proportional pixel font for the phone LCD. Writes ../phone-src/src2/lcd/fontdata.js
and a preview PNG. Rows: 0 = accent row for capitals, 1-7 = cap height (baseline under row 7),
3-7 = x-height, 8-9 = descenders."""
