# ------------------------------------------------------------ export
data = {}
for ch, rows in G.items():
    w = len(rows[0])
    bits = []
    for r in rows:
        v = 0
        for x, c in enumerate(r):
            if c == '#':
                v |= 1 << x
        bits.append(v)
    data[ch] = [w] + bits

out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'lcd')
os.makedirs(out_dir, exist_ok=True)
with open(os.path.join(out_dir, 'fontdata.js'), 'w') as f:
    f.write('// Pixel font drawn for this phone. [width, row0..row9 bitmasks]\n')
    f.write('export const FONT = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')

